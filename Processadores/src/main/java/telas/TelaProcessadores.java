    private void montaTabela() {
        ArrayList<Processador> itens = pp.recuperarTodos();

        String[] colunas = {"ID", "Nome", "Fabricante", "Nucleos", "Threads"};

        DefaultTableModel modelo = new DefaultTableModel(colunas, 0);

        for (int i = 0; i < itens.size(); i++) {
            Processador o = itens.get(i);
            Object[] linha = {o.getCodigo(), o.getNome(), o.getFabricante(), o.getNucleos(), o.getThreads()};
            modelo.addRow(linha);
        }

        tblItens.setModel(modelo);

        // opcional
        tblItens.getColumnModel().getColumn(0).setMinWidth(15);
        tblItens.getColumnModel().getColumn(0).setPreferredWidth(30);
        tblItens.getColumnModel().getColumn(0).setMaxWidth(30);
    }

