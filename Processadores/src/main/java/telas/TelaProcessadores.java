    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        String idString = String.valueOf(tblItens.getValueAt(tblItens.getSelectedRow(), 0));
        int id = Integer.parseInt(idString);

        pp.excluir(id);
        montaTabela();
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
         String idString = String.valueOf(tblItens.getValueAt(tblItens.getSelectedRow(), 0));
        int id = Integer.parseInt(idString);

        Processador p = pp.recuperarUm(id);
        if (p != null) {
            codigo = p.getCodigo();
            txtNome.setText(p.getNome());
            txtFabricante.setText(p.getFabricante());
            txtNucleos.setText(Integer.toString(p.getNucleos()));
            txtThreads.setText(Integer.toString(p.getThreads()));
            
            btnSalvar.setText("Atualizar");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

