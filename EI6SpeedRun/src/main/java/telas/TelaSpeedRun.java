    private void montaTabela() {
        ArrayList<SpeedRun> itens = csr.recuperarTodos();

        String[] colunas = {"ID", "Jogador", "Jogo", "Duração"};

        DefaultTableModel modelo = new DefaultTableModel(colunas, 0);

        for (int i = 0; i < itens.size(); i++) {
            SpeedRun sr = itens.get(i);
            Object[] linha = {sr.getCodigo(), sr.getJogador(), sr.getJogo(), sr.getTempo()};
            modelo.addRow(linha);
        }

        tbl1Itens.setModel(modelo);

        DefaultTableCellRenderer centralizado = new DefaultTableCellRenderer(); // código para centralizar as respostas na table
        centralizado.setHorizontalAlignment(SwingConstants.CENTER); //precisou de 2 import

        for (int i = 0; i < tbl1Itens.getColumnCount(); i++) {
            tbl1Itens.getColumnModel().getColumn(i).setCellRenderer(centralizado);
        }
        // Opcional 
        tbl1Itens.getColumnModel().getColumn(0).setMinWidth(15); //largura min
        tbl1Itens.getColumnModel().getColumn(0).setPreferredWidth(30); //largura preferida, tenta deixar com 30 px
        tbl1Itens.getColumnModel().getColumn(0).setMaxWidth(30); //largura max

    }

