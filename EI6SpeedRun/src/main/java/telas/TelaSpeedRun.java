    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        SpeedRun sr = new SpeedRun(
                txtJogador.getText(),
                txtJogo.getText(),
                Double.parseDouble(txtTempo.getText())
        );

        if (codigo == 0) {
            csr.salvar(sr);
        } else {
            sr.setCodigo(codigo);
            csr.editar(sr);
            codigo = 0;
        }
        btnSalvar.setText("Salvar");
        montaTabela();

        txtJogador.setText("");
        txtJogo.setText("");
        txtTempo.setText("");

        txtJogador.requestFocus();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        String idString = String.valueOf(tbl1Itens.getValueAt(tbl1Itens.getSelectedRow(), 0)); //quando selecionar a linha com o mouse
        int id = Integer.parseInt(idString);

        SpeedRun sr = csr.recuperarUm(id);
        if (sr != null) {
            codigo = sr.getCodigo();
            txtJogador.setText(sr.getJogador());
            txtJogo.setText(sr.getJogo());
            txtTempo.setText(Double.toString(sr.getTempo()));

            btnSalvar.setText("Atualizar");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

