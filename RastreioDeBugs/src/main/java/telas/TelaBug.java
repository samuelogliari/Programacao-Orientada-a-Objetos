    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Bug b = new Bug(
                txtNome.getText(),
                txtTecnologia.getText(),
                txtDificuldade.getText(),
                (int) spnCoposDeCafe.getValue()
        );

        if (codigo == 0) {
            cb.salvar(b);
        } else {
            b.setId(codigo);
            cb.editar(b);
            codigo = 0;
        }
        btnSalvar.setText("Salvar");
        montaTabela();

        txtNome.setText("");
        txtTecnologia.setText("");
        txtDificuldade.setText("");
        spnCoposDeCafe.setValue(0);

        txtNome.requestFocus();


    }//GEN-LAST:event_btnSalvarActionPerformed

