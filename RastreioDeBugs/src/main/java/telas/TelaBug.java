    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        String idString = String.valueOf(tbl1.getValueAt(tbl1.getSelectedRow(), 0)); //quando selecionar a linha com o mouse
        int id = Integer.parseInt(idString);

        Bug b = cb.recuperarUm(id);
        if (b != null) {
            codigo = b.getId();
            txtNome.setText(b.getNome());
            txtTecnologia.setText(b.getTecnologia());
            txtDificuldade.setText(b.getDificuldade());
            spnCoposDeCafe.setValue(b.getCoposDeCafe());

            btnSalvar.setText("Atualizar");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int confirmacao = Mensagem.confirmacao("Deseja realmente excluir?");
        if (confirmacao == 0) {
            int codigo = Integer.parseInt(String.valueOf(tbl1.getValueAt(tbl1.getSelectedRow(), 0)));
            cb.excluir(codigo);
            montaTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

