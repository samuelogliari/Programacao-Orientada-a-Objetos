    private void montaTabela() {
        ArrayList<Bug> itens = cb.recuperarTodos();

        String[] colunas = {"ID", "Nome", "Tecnologia", "Dificuldade", "Café"};

        DefaultTableModel modelo = new DefaultTableModel(colunas, 0);

        for (int i = 0; i < itens.size(); i++) {
            Bug b = itens.get(i);
            Object[] linha = {b.getId(), b.getNome(), b.getTecnologia(), b.getDificuldade(), b.getCoposDeCafe()};
            modelo.addRow(linha);
        }

        tbl1.setModel(modelo);

        DefaultTableCellRenderer centralizado = new DefaultTableCellRenderer();
        centralizado.setHorizontalAlignment(SwingConstants.CENTER);

        for (int i = 0; i < tbl1.getColumnCount(); i++) {
            tbl1.getColumnModel().getColumn(i).setCellRenderer(centralizado);
        }

        tbl1.getColumnModel().getColumn(0).setMinWidth(15);
        tbl1.getColumnModel().getColumn(0).setPreferredWidth(30);
        tbl1.getColumnModel().getColumn(0).setMaxWidth(30);
    }

